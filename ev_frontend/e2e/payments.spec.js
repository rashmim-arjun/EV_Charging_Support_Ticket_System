import { test, expect } from '@playwright/test'

test('customer proof, manual rejection, correction and verification remain separate from ticket resolution', async ({page},testInfo) => {
  const errors=[]
  page.on('pageerror',e => errors.push(e.message))
  await page.goto('/new')
  await page.getByRole('textbox',{name:'Complaint *',exact:true}).fill('My charging visit did not start. Please review the session and my payment submission.')
  await page.getByRole('button',{name:'Save ticket before investigation'}).click()
  const panel=page.getByRole('region',{name:'Payment verification',exact:true})
  await expect(panel.getByText('Not submitted',{exact:true})).toBeVisible()
  const caseId=page.url().split('/').pop()
  const apiPath=`/api/v1/tickets/${caseId}/payment`
  await panel.getByRole('textbox',{name:'Transaction reference'}).fill('UPI-123456789012')
  await panel.getByLabel('Payment screenshot (optional)').setInputFiles({name:'receipt.png',mimeType:'image/png',
    buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a7nEAAAAASUVORK5CYII=','base64')})
  await panel.getByRole('button',{name:'Submit payment information'}).click()
  await expect(panel.getByText('Submitted - not verified',{exact:true})).toBeVisible()
  await expect(panel.getByText('UPI-123456789012',{exact:true})).toBeVisible()
  await page.reload()
  await expect(panel.getByText('Submitted - not verified',{exact:true})).toBeVisible()
  const forbidden=await page.request.post(apiPath+'/review',{data:{version:1,decision:'verified',reason:'Customer attempting approval'}})
  expect(forbidden.status()).toBe(403)
  await panel.getByText('Manual reviewer actions',{exact:true}).click()
  await panel.getByRole('combobox',{name:'Payment reviewer'}).selectOption('rev-payment-001')
  await expect(panel.getByRole('button',{name:'Download submitted screenshot'})).toBeEnabled()
  const download=page.waitForEvent('download')
  await panel.getByRole('button',{name:'Download submitted screenshot'}).click()
  expect((await download).suggestedFilename()).toBe('receipt.png')
  await panel.getByRole('textbox',{name:'Manual review reason'}).fill('Beginning a manual review of the supplied screenshot and reference.')
  await panel.getByRole('button',{name:'Start manual review'}).click()
  await expect(panel.getByText('Under manual review',{exact:true})).toBeVisible()
  await panel.getByRole('textbox',{name:'Manual review reason'}).fill('The supplied reference does not match the receipt; correction is required.')
  await panel.getByRole('button',{name:'Reject payment',exact:true}).click()
  await expect(panel.getByText('Rejected',{exact:true})).toBeVisible()
  await expect(panel.getByText(/Rejection reason: The supplied reference/)).toBeVisible()
  await panel.getByRole('textbox',{name:'Transaction reference'}).fill('UPI-CORRECTED123456')
  await panel.getByRole('button',{name:'Submit payment information'}).click()
  await expect(panel.getByText('Submitted - not verified',{exact:true})).toBeVisible()
  await panel.getByRole('textbox',{name:'Manual review reason'}).fill('Beginning a manual review of the corrected reference.')
  await panel.getByRole('button',{name:'Start manual review'}).click()
  await expect(panel.getByText('Under manual review',{exact:true})).toBeVisible()

  // Resolving the charging enquiry must leave the payment decision pending.
  await page.getByRole('button',{name:'Investigate ticket',exact:true}).click()
  await expect(page.getByText(/diagnosis v1/)).toBeVisible()
  await page.getByRole('button',{name:'Record verified resolution'}).click()
  await page.getByRole('combobox',{name:'Reviewer *',exact:true}).selectOption('rev-001')
  await page.getByRole('combobox',{name:'Verified root cause *',exact:true}).selectOption('inconclusive')
  await page.getByRole('textbox',{name:'Corrective action *',exact:true}).fill('Charging enquiry reviewed; more session evidence is required. Payment remains under separate manual review.')
  await page.getByRole('button',{name:/Submit verified resolution/}).click()
  await expect(page.getByRole('heading',{name:'Verified resolution',exact:true})).toBeVisible()
  await expect(panel.getByText('Under manual review',{exact:true})).toBeVisible()
  await panel.getByRole('textbox',{name:'Manual review reason'}).fill('Manual reviewer reconciliation of the corrected reference completed; no automated gateway lookup.')
  await panel.getByRole('button',{name:'Verify payment manually'}).click()
  await expect(panel.getByText('Verified by manual reviewer',{exact:true})).toBeVisible()
  await page.reload()
  await expect(panel.getByText('Verified by manual reviewer',{exact:true})).toBeVisible()
  const payment=await (await page.request.get(apiPath)).json()
  expect(payment.status).toBe('verified')
  expect(payment.reviewer_id).toBe('rev-payment-001')
  expect(payment.submissions).toHaveLength(2)
  expect(payment.history.map(h => h.action)).toEqual(['payment_submitted','payment_under_review','payment_rejected','payment_submitted','payment_under_review','payment_verified'])
  expect((await (await page.request.get(`/api/v1/tickets/${caseId}`)).json()).state).toBe('resolved')
  expect(await page.evaluate(() => document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:`test-results/${testInfo.project.name}-payment-verification.png`,fullPage:true})
  expect(errors).toEqual([])
})
