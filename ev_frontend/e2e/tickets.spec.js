import { test,expect } from '@playwright/test'

test('customer support ticket investigation, cautious priority, override, resolution and closure',async({page},testInfo)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/communication')
  await page.getByRole('spinbutton',{name:'Simulation seed'}).fill(testInfo.project.name==='mobile'?'902':'901')
  await page.getByRole('combobox',{name:'Scenario',exact:true}).selectOption('vehicle_bms_fault')
  await page.getByRole('button',{name:'Generate sessions',exact:true}).click()
  await page.getByRole('link',{name:'Open support ticket for this session'}).click()
  await expect(page.getByRole('textbox',{name:/Session reference/})).not.toHaveValue('')
  await page.getByRole('textbox',{name:/^Complaint/}).fill('My charging stopped before the car reached my target. Please investigate the visit.')
  await page.getByRole('button',{name:'Save ticket before investigation'}).click()
  await expect(page.getByRole('heading',{name:'Support ticket management'})).toBeVisible()
  await expect(page.getByRole('combobox',{name:'Ticket state',exact:true})).toHaveValue('new')
  await page.getByRole('button',{name:'Investigate ticket',exact:true}).click()
  const url=page.url()
  await expect(page.getByText('Owner: Vehicle / BMS specialists',{exact:true})).toBeVisible()
  await expect(page.getByText('P1',{exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Inspect correlated session logs'}).click()
  await expect(page.getByRole('heading',{name:'Chronological session logs'})).toBeVisible()
  await page.goto(url)
  await page.getByRole('combobox',{name:'Assigned team',exact:true}).selectOption('triage')
  await page.getByRole('listbox',{name:'Supporting teams'}).selectOption('vehicle_specialists')
  await page.getByRole('textbox',{name:'Assignment / escalation reason'}).fill('Escalate to triage for joint safety review with vehicle specialists')
  await page.getByRole('button',{name:'Save ticket decision'}).click()
  await expect(page.getByText('Owner: Support triage',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Investigate again',exact:true}).click()
  await expect(page.getByText(/diagnosis v2/)).toBeVisible()
  await expect(page.getByText('Owner: Support triage',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Record verified resolution'}).click()
  await page.getByRole('combobox',{name:'Reviewer *',exact:true}).selectOption('rev-001')
  await page.getByRole('textbox',{name:'Corrective action *',exact:true}).fill('Reviewed BMS safety evidence and arranged a vehicle specialist inspection.')
  await page.getByRole('button',{name:/Submit verified resolution/}).click()
  await expect(page.getByRole('heading',{name:'Verified resolution'})).toBeVisible()
  await page.getByRole('combobox',{name:'Ticket state',exact:true}).selectOption('closed')
  await page.getByRole('textbox',{name:'Assignment / escalation reason'}).fill('Verified resolution recorded and customer follow-up completed')
  await page.getByRole('button',{name:'Save ticket decision'}).click()
  await expect(page.getByRole('combobox',{name:'Ticket state',exact:true})).toHaveValue('closed')
  await expect(page.getByText('Investigation and escalation history (7)',{exact:true})).toBeVisible()
  await page.getByText(/Investigation and escalation history/).click()
  await expect(page.getByRole('cell').filter({hasText:'Escalate to triage for joint safety review with vehicle specialists'}).first()).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:`test-results/${testInfo.project.name}-tickets.png`,fullPage:true})
  expect(errors).toEqual([])
})
