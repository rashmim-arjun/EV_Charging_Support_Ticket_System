import { test, expect } from '@playwright/test'

test('complete complaint, evidence, feedback, learning, evaluation and review import', async ({ page }, testInfo) => {
  const failures = []
  page.on('pageerror', error => failures.push(error.message))
  const nav = async name => {
    const menu = page.getByRole('navigation', { name: 'Main navigation' })
    if (!(await menu.isVisible())) await page.getByRole('button', { name: 'Open navigation' }).click()
    await menu.getByRole('link', { name, exact: true }).click()
  }
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  await nav('New complaint')
  await page.getByText('Demo examples', { exact: true }).click()
  await page.getByRole('button', { name: 'Session never started (matches seeded logs)' }).click()
  await page.getByRole('button', { name: /Run diagnosis/ }).click()
  await expect(page).toHaveURL(/\/cases\/C-/)
  await expect(page.getByRole('heading', { name: 'Session fails to start', exact: true })).toBeVisible()
  await expect(page.getByText(/Synthetic calibrated confidence/)).toBeVisible()
  await page.getByRole('button', { name: 'Evidence', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Matching evidence/ })).toBeVisible()
  await expect(page.getByText(/Event timeline shows/).first()).toBeVisible()
  await page.getByRole('button', { name: /Agent trace/ }).click()
  await expect(page.getByRole('heading', { name: 'Agent reasoning trace' })).toBeVisible()
  await page.getByRole('button', { name: 'Verify & learn' }).click()
  await page.getByRole('combobox', { name: 'Reviewer *', exact: true }).selectOption('rev-001')
  await page.getByRole('textbox', { name: 'Corrective action *', exact: true }).fill('Technician verified a start timeout and restored the charger.')
  await page.getByRole('button', { name: /Submit verified resolution/ }).click()
  await expect(page.getByRole('heading', { name: 'Verified resolution' })).toBeVisible()
  await page.getByRole('button', { name: /Preview changes/ }).click()
  await expect(page.getByRole('columnheader', { name: 'Old', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Apply learning/ }).click()
  await expect(page.getByText('Learning from this case has already been applied.')).toBeVisible()
  await nav('Knowledge & learning')
  await page.getByRole('button', { name: /Tool priors/ }).click()
  await expect(page.getByRole('columnheader', { name: 'Observations', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Change log/ }).click()
  await expect(page.getByRole('button', { name: 'Revert', exact: true }).first()).toBeVisible()
  await nav('Support tickets')
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('resolved')
  await expect(page.getByRole('link', { name: /^C-/ }).first()).toBeVisible()
  await nav('Evaluation')
  await page.getByLabel('Cases / template', { exact: true }).fill('1')
  await page.getByLabel('Seed', { exact: true }).fill('7')
  await page.getByRole('button', { name: /Run evaluation/ }).click()
  await expect(page.getByText(/25 cases/)).toBeVisible({ timeout: 30000 })
  await expect(page.getByRole('heading', { name: 'Adaptive agent: precision, recall and F1' })).toBeVisible()
  const csv = `text,data_origin\nAcademic import ${testInfo.project.name} call 9812345678,manual_test\n`
  await nav('Review import')
  await expect(page.getByRole('combobox', { name: 'App', exact: true })).toHaveCount(0)
  await page.getByLabel('Review file').setInputFiles({ name: 'reviews.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await page.getByRole('button', { name: /Import$/, exact: false }).click()
  await expect(page.getByText(`Academic import ${testInfo.project.name} call [PHONE]`, { exact: true })).toBeVisible()
  await expect(page.getByText('9812345678', { exact: false })).toHaveCount(0)
  await expect(page.getByRole('columnheader', { name: 'App', exact: true })).toHaveCount(0)
  await page.screenshot({ path: `test-results/${testInfo.project.name}-reviews.png`, fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(failures).toEqual([])
})
