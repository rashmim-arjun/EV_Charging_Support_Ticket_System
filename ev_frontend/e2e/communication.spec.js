import { test, expect } from '@playwright/test'

test('communication session monitoring, correlation, diagnosis, feedback and comparison', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await page.goto('/communication')
  await expect(page.getByRole('heading', { name: 'Communication monitoring', exact: true })).toBeVisible()
  await page.getByRole('spinbutton', { name: 'Simulation seed' }).fill(testInfo.project.name === 'mobile' ? '202' : '101')
  await page.getByRole('combobox', { name: 'Scenario', exact: true }).selectOption('network_loss')
  await page.getByRole('button', { name: 'Generate sessions', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Chronological session logs' })).toBeVisible()
  await expect(page.getByRole('cell').filter({ hasText: 'transport.dropped' }).first()).toBeVisible()
  await expect(page.getByText('Connection: message_loss')).toBeVisible()
  await page.getByRole('button', { name: /Message flow/ }).click()
  await expect(page.getByRole('img', { name: 'Chronological messages between component columns' })).toBeVisible()
  await page.getByRole('button', { name: /Communication failures & conflicts/ }).click()
  await expect(page.getByText(/explicitly dropped by the transport/)).toBeVisible()
  await page.getByRole('button', { name: 'Diagnose session', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Network Loss', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Open case for reviewer feedback & learning' }).click()
  await expect(page).toHaveURL(/\/cases\/C-/)
  await page.getByRole('button', { name: 'Verify & learn' }).click()
  await page.getByRole('combobox', { name: 'Reviewer *', exact: true }).selectOption('rev-001')
  await page.getByRole('textbox', { name: 'Corrective action *', exact: true }).fill('Reviewed correlated transport logs and confirmed dropped charging request.')
  await page.getByRole('button', { name: /Submit verified resolution/ }).click()
  await page.getByRole('button', { name: /Preview changes/ }).click()
  await expect(page.getByRole('columnheader', { name: 'Old', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Apply learning/ }).click()
  await expect(page.getByText('Learning from this case has already been applied.')).toBeVisible()
  if (!(await nav.isVisible())) await page.getByRole('button', { name: 'Open navigation' }).click()
  await nav.getByRole('link', { name: 'Communication monitoring', exact: true }).click()
  await page.getByRole('combobox', { name: 'Scenario', exact: true }).selectOption('none')
  await page.getByRole('button', { name: 'Generate sessions', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Chronological session logs' })).toBeVisible()
  for (const [component, event] of [['BMS', 'battery.telemetry'], ['Payment', 'payment.result'], ['Network', 'transport.delivered']]) {
    const card = page.getByRole('group', { name: `${component} component logs`, exact: true })
    await expect(card.getByText(/Last recorded \(UTC\)/)).toBeVisible()
    await page.getByRole('textbox', { name: 'Search events' }).fill('unmatched-search')
    await card.getByRole('button', { name: new RegExp(`View ${component} logs`) }).click()
    await expect(page.getByRole('textbox', { name: 'Search events' })).toHaveValue('')
    await expect(page.getByRole('cell').filter({ hasText: event }).first()).toBeVisible()
  }
  await page.getByRole('button', { name: 'Diagnose session', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'No fault established' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Scenario', exact: true }).selectOption('inconclusive')
  await page.getByRole('button', { name: 'Generate sessions', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Chronological session logs' })).toBeVisible()
  for (const component of ['BMS', 'Payment', 'Network']) {
    await page.getByRole('button', { name: `View ${component} logs (0)`, exact: true }).click()
    await expect(page.getByText(`No ${component} records were captured for this session.`, { exact: false })).toBeVisible()
  }
  await page.screenshot({ path: `test-results/${testInfo.project.name}-missing-component-logs.png`, fullPage: true })
  await page.getByRole('button', { name: 'Diagnose session', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Inconclusive: insufficient or conflicting evidence' })).toBeVisible()
  await page.getByRole('button', { name: 'Run communication evaluation', exact: true }).click()
  await expect(page.getByText(/36 sessions · train 12 \/ validation 12 \/ test 12/)).toBeVisible({ timeout: 30000 })
  await expect(page.getByRole('cell', { name: 'Multi Component', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: `test-results/${testInfo.project.name}-communication.png`, fullPage: true })
  expect(errors).toEqual([])
})
