import { test, expect } from '@playwright/test'

test('normal and urgent tickets have clear outcomes, accessible navigation and responsive queues', async ({ page }, testInfo) => {
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  const navigate=async name=>{
    const menu=page.getByRole('navigation',{name:'Main navigation'})
    if (!(await menu.isVisible())) await page.getByRole('button',{name:'Open navigation'}).click()
    await menu.getByRole('link',{name,exact:true}).click()
  }
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Dashboard',exact:true})).toBeVisible()
  await expect(page.getByRole('link',{name:'View all tickets',exact:true})).toBeVisible()
  await expect(page.getByText('Demo evaluation accuracy',{exact:true})).toBeVisible()
  if (testInfo.project.name==='mobile') await expect(page.getByRole('navigation',{name:'Main navigation'})).toBeHidden()
  await navigate('Communication monitoring')
  await page.getByRole('spinbutton',{name:'Simulation seed'}).fill(testInfo.project.name==='mobile'?'1004':'1003')
  await page.getByRole('combobox',{name:'Scenario',exact:true}).selectOption('none')
  await page.getByRole('button',{name:'Generate sessions',exact:true}).click()
  await page.getByRole('link',{name:'Open support ticket for this session'}).click()
  await page.getByRole('textbox',{name:'Complaint *',exact:true}).fill('Charging completed normally. Please confirm that my receipt and session records agree.')
  const saved=page.waitForResponse(r=>r.url().endsWith('/api/v1/cases')&&r.request().method()==='POST')
  await page.getByRole('button',{name:/Run diagnosis/}).click()
  const full=(await (await saved).json()).case
  expect(full.diagnosis.outcome).toBe('no_fault_established')
  await expect(page.getByRole('heading',{name:'No fault established',exact:true})).toBeVisible()
  await expect(page.getByRole('combobox',{name:'Ticket state',exact:true})).toHaveCount(0)
  const summary=page.getByRole('region',{name:'Investigation summary'})
  await expect(summary.getByText(/No corrective work is indicated/)).toBeVisible()
  await page.screenshot({path:`test-results/${testInfo.project.name}-final-healthy-ticket.png`,fullPage:true})
  await navigate('Support tickets')
  await expect(page.getByRole('link',{name:full.case.case_id,exact:true})).toBeVisible()
  await expect(page.getByRole('combobox',{name:'App',exact:true})).toHaveCount(0)
  if(testInfo.project.name==='mobile') await expect(page.locator('.mobile-ticket-list')).toBeVisible()
  await page.screenshot({path:`test-results/${testInfo.project.name}-final-ticket-queue.png`,fullPage:true})
  await navigate('New complaint')
  await page.getByRole('textbox',{name:'Complaint *',exact:true}).fill('There is a burning smell near the charging cable. Please arrange an urgent review.')
  await page.getByRole('button',{name:/Run diagnosis/}).click()
  await expect(page.getByRole('heading',{name:'Investigation summary',exact:true})).toBeVisible()
  await expect(page.getByRole('region',{name:'Investigation summary'}).getByText('P0',{exact:true})).toBeVisible()
  await expect(page.getByText(/Immediate human safety review is required/)).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
